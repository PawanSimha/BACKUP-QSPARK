#!/usr/bin/env python
"""Export the SQLite source DB to an Oracle INSERT script (oracle/03_data.sql).

Usage:
    .venv\\Scripts\\python.exe tools\\export_sqlite_to_oracle.py

Reads database/parking_local.db (authoritative source, per D8) and writes
oracle/03_data.sql with ~690 INSERTs in FK-safe order, explicit IDs,
NULL for '', metadata timestamps shifted +5:30 (Asia/Kolkata), money rounded
to 2dp, SET DEFINE OFF header. Password hashes are included -> file is
gitignored (see .gitignore).
"""
import os
import sqlite3
from datetime import datetime, timedelta

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DB = os.path.join(REPO, "database", "parking_local.db")
OUT = os.path.join(REPO, "oracle", "03_data.sql")

# FK-safe insert order (per oracle conversation with AI.md sec. 11)
TABLE_ORDER = [
    "users", "floors", "vehicle_types", "cancellation_rules", "parking_slots",
    "bookings", "wallet_transactions", "booking_events", "audit_logs",
    "revenue_collections", "system_settings",
]

# Oracle table name per SQLite table
ORACLE_TABLE = {t: "QSPARK_" + t.upper() for t in TABLE_ORDER}
# users -> QSPARK_USERS, etc. (SQLite table names are already plural-ish matching)

# All timestamp columns (emitted as ANSI TIMESTAMP literals, NLS-independent).
TIMESTAMP_COLS = {'created_at', 'updated_at', 'hold_expires_at', 'booked_from', 'booked_until'}

# Columns whose values are timestamps that must shift +5:30 (metadata + hold expiry + event ts).
# booked_from / booked_until are NOT shifted.
SHIFT_TS_COLS = {
    "users": {"created_at", "updated_at"},
    "floors": {"created_at", "updated_at"},
    "vehicle_types": {"created_at", "updated_at"},
    "cancellation_rules": {"created_at", "updated_at"},
    "parking_slots": {"created_at", "updated_at"},
    "bookings": {"hold_expires_at", "created_at", "updated_at"},
    "wallet_transactions": {"created_at", "updated_at"},
    "booking_events": {"created_at", "updated_at"},
    "audit_logs": {"created_at", "updated_at"},
    "revenue_collections": {"created_at", "updated_at"},
    "system_settings": {"created_at", "updated_at"},
}

SHIFT = timedelta(minutes=330)


def sql_str(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        # money already 2dp in source; keep as-is
        return repr(v) if isinstance(v, float) else str(v)
    s = str(v)
    if s == "":
        return "NULL"
    # timestamp shift?
    return None  # handled by caller for ts cols


def normalize_ts(val):
    """Normalize invalid 24:00 hours to 00:00 next day (Oracle rejects hour 24)."""
    if val is None or val == "":
        return val
    parts = str(val).split(" ")
    if len(parts) == 2 and parts[1].startswith("24:"):
        date_part, time_part = parts
        mmss = time_part[3:]  # MM:SS
        try:
            d = datetime.strptime(date_part, "%Y-%m-%d").date() + timedelta(days=1)
            return d.strftime("%Y-%m-%d") + " 00:" + mmss
        except ValueError:
            pass
    return val


def shift_ts(val):
    val = normalize_ts(val)
    if val is None or val == "":
        return None
    try:
        dt = datetime.strptime(val, "%Y-%m-%d %H:%M:%S")
    except ValueError:
        try:
            dt = datetime.strptime(val, "%Y-%m-%d %H:%M:%S.%f")
        except ValueError:
            return val
    return (dt + SHIFT).strftime("%Y-%m-%d %H:%M:%S")


def fmt_value(col, val, shift):
    if col in TIMESTAMP_COLS:
        val = normalize_ts(val)
    if shift:
        val = shift_ts(val)
    if val is None or val == "":
        return "NULL"
    if isinstance(val, bool):
        return "1" if val else "0"
    if isinstance(val, (int,)):
        return str(val)
    if isinstance(val, float):
        return f"{val:.2f}"
    s = str(val)
    # timestamp -> ANSI literal (NLS-independent)
    if col in TIMESTAMP_COLS:
        return "TIMESTAMP '%s'" % s.replace("'", "''")
    # default text
    return "'" + s.replace("'", "''") + "'"


def main():
    conn = sqlite3.connect(SRC_DB)
    conn.row_factory = sqlite3.Row
    cur = conn.cursor()

    lines = []
    lines.append("-- QSPARK data migration: SQLite -> Oracle (NOV_2026_BATCH)")
    lines.append("-- Generated by tools/export_sqlite_to_oracle.py")
    lines.append("-- Source: database/parking_local.db (authoritative, per D8)")
    lines.append("-- Timestamps: created_at/updated_at/hold_expires_at/event ts shifted +5:30 (Asia/Kolkata).")
    lines.append("-- booked_from / booked_until are NOT shifted.")
    lines.append("-- Empty strings exported as NULL (Oracle treats '' as NULL).")
    lines.append("SET DEFINE OFF;")
    lines.append("")

    total = 0
    for table in TABLE_ORDER:
        cols_info = cur.execute(f"PRAGMA table_info({table})").fetchall()
        col_names = [r["name"] for r in cols_info]
        rows = cur.execute(f"SELECT * FROM {table}").fetchall()
        ts_cols = SHIFT_TS_COLS.get(table, set())
        otbl = ORACLE_TABLE[table]
        lines.append(f"-- {table}: {len(rows)} rows")
        for row in rows:
            vals = []
            for c in col_names:
                v = row[c]
                vals.append(fmt_value(c, v, c in ts_cols))
            col_list = ", ".join(col_names)
            val_list = ", ".join(vals)
            lines.append(f"INSERT INTO {otbl} ({col_list}) VALUES ({val_list});")
            total += 1
        lines.append("")

    lines.append("COMMIT;")
    lines.append("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"Wrote {OUT}: {total} INSERT statements across {len(TABLE_ORDER)} tables.")


if __name__ == "__main__":
    main()
