-- ============================ 1. users ============================
CREATE TABLE QSPARK_USERS (
    user_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    admin_id      VARCHAR2(50 CHAR),
    full_name     VARCHAR2(100 CHAR) NOT NULL,
    email         VARCHAR2(255 CHAR),
    phone         VARCHAR2(20 CHAR)  NOT NULL,
    gender        VARCHAR2(20 CHAR)  CHECK (gender IN ('MALE','FEMALE','OTHER','PREFER_NOT_TO_SAY')),
    company_name  VARCHAR2(200 CHAR),
    username      VARCHAR2(100 CHAR),
    password_hash VARCHAR2(256 CHAR),
    role          VARCHAR2(20 CHAR)  NOT NULL CHECK (role IN ('CUSTOMER','ADMIN','SUPER_ADMIN')),
    wallet_balance NUMBER(14,2)     DEFAULT 1000 NOT NULL,
    account_status VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL
                   CHECK (account_status IN ('PENDING','ACTIVE','BLOCKED','DELETED')),
    created_by    NUMBER,
    created_at    TIMESTAMP(0)      DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by    NUMBER,
    updated_at    TIMESTAMP(0)      DEFAULT SYSTIMESTAMP NOT NULL,
    reserved1     VARCHAR2(500 CHAR),
    reserved2     VARCHAR2(500 CHAR),
    CONSTRAINT pk_qspark_users PRIMARY KEY (user_id),
    CONSTRAINT uq_qspark_users_admin_id UNIQUE (admin_id),
    CONSTRAINT uq_qspark_users_email UNIQUE (email),
    CONSTRAINT uq_qspark_users_username UNIQUE (username),
    CONSTRAINT chk_qspark_users_role_admin CHECK ((role = 'CUSTOMER' AND admin_id IS NULL) OR (role IN ('ADMIN','SUPER_ADMIN') AND admin_id IS NOT NULL)),
    CONSTRAINT chk_qspark_users_login CHECK (username IS NOT NULL OR email IS NOT NULL),
    CONSTRAINT chk_qspark_users_active_pwd CHECK ((account_status = 'ACTIVE' AND password_hash IS NOT NULL) OR account_status <> 'ACTIVE'),
    CONSTRAINT chk_qspark_users_wallet CHECK (wallet_balance >= 0),
    CONSTRAINT fk_qspark_users_created_by FOREIGN KEY (created_by) REFERENCES QSPARK_USERS(user_id) ON DELETE SET NULL,
    CONSTRAINT fk_qspark_users_updated_by FOREIGN KEY (updated_by) REFERENCES QSPARK_USERS(user_id) ON DELETE SET NULL
);

