-- oracle/04_identity.sql
-- Sequences+triggers identity setup for Oracle 19c.
-- Since ALTER TABLE ... ADD IDENTITY raises ORA-00902 on Oracle 19c,
-- we use BEFORE INSERT triggers + sequences to auto-populate PK values.
-- Triggers have WHEN (NEW.pk_col IS NULL) to allow explicit IDs while auto-populating NULL.
-- Run AFTER oracle/03_data.sql has been committed.

-- Sequences (create if not already present)
CREATE QSPARK_USERS_SEQ START WITH 52 NOCACHE NOCYCLE;
CREATE QSPARK_FLOORS_SEQ START WITH 5 NOCACHE NOCYCLE;
CREATE QSPARK_VEHICLE_TYPES_SEQ START WITH 3 NOCACHE NOCYCLE;
CREATE QSPARK_CANCELLATION_RULES_SEQ START WITH 5 NOCACHE NOCYCLE;
CREATE QSPARK_PARKING_SLOTS_SEQ START WITH 257 NOCACHE NOCYCLE;
CREATE QSPARK_BOOKINGS_SEQ START WITH 57 NOCACHE NOCYCLE;
CREATE QSPARK_WALLET_TRANSACTIONS_SEQ START WITH 138 NOCACHE NOCYCLE;
CREATE QSPARK_BOOKING_EVENTS_SEQ START WITH 101 NOCACHE NOCYCLE;
CREATE QSPARK_AUDIT_LOGS_SEQ START WITH 17 NOCACHE NOCYCLE;
CREATE QSPARK_REVENUE_COLLECTIONS_SEQ START WITH 62 NOCACHE NOCYCLE;
CREATE QSPARK_SYSTEM_SETTINGS_SEQ START WITH 2 NOCACHE NOCYCLE;

-- Triggers: auto-populate PK from sequence when NULL on INSERT
CREATE OR REPLACE TRIGGER TRG_QSPARK_USERS_BI
BEFORE INSERT ON QSPARK_USERS
FOR EACH ROW
WHEN (NEW.user_id IS NULL)
BEGIN
  SELECT QSPARK_USERS_SEQ.NEXTVAL INTO :NEW.user_id FROM DUAL;
END;
/

