-- ============================ TRIGGERS ============================
CREATE OR REPLACE TRIGGER trg_qspark_no_overlapping_bookings
BEFORE INSERT ON QSPARK_BOOKINGS
FOR EACH ROW
WHEN (NEW.booking_status IN ('HELD','CONFIRMED'))
BEGIN
    DECLARE v_cnt NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_cnt FROM QSPARK_BOOKINGS b
        WHERE b.slot_id = :NEW.slot_id
          AND b.booking_status IN ('HELD','CONFIRMED')
          AND b.booked_from < :NEW.booked_until
          AND b.booked_until > :NEW.booked_from;
        IF v_cnt > 0 THEN
            RAISE_APPLICATION_ERROR(-20001, 'overlapping active booking for slot');
        END IF;
    END;
END;
/

CREATE OR REPLACE TRIGGER trg_qspark_booking_status_transitions
BEFORE UPDATE OF booking_status ON QSPARK_BOOKINGS
FOR EACH ROW
WHEN (NEW.booking_status <> OLD.booking_status)
BEGIN
    IF NOT (
        (:OLD.booking_status = 'HELD' AND :NEW.booking_status IN ('CONFIRMED','CANCELLED','EXPIRED')) OR
        (:OLD.booking_status = 'CONFIRMED' AND :NEW.booking_status IN ('COMPLETED','CANCELLED'))
    ) THEN
        RAISE_APPLICATION_ERROR(-20002, 'illegal booking status transition');
    END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_qspark_exit_requires_entry
BEFORE INSERT ON QSPARK_BOOKING_EVENTS
FOR EACH ROW
WHEN (NEW.event_type = 'EXIT')
BEGIN
    DECLARE v_cnt NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_cnt FROM QSPARK_BOOKING_EVENTS
        WHERE booking_id = :NEW.booking_id AND event_type = 'ENTRY';
        IF v_cnt = 0 THEN
            RAISE_APPLICATION_ERROR(-20003, 'EXIT before ENTRY not allowed');
        END IF;
    END;
END;
/

CREATE OR REPLACE TRIGGER trg_qspark_protect_active_user_delete
BEFORE DELETE ON QSPARK_USERS
FOR EACH ROW
BEGIN
    DECLARE v_cnt NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_cnt FROM QSPARK_BOOKINGS
        WHERE user_id = :OLD.user_id AND booking_status IN ('HELD','CONFIRMED');
        IF v_cnt > 0 THEN
            RAISE_APPLICATION_ERROR(-20004, 'cannot physically delete user with active bookings; soft delete instead');
        END IF;
    END;
END;
/

